#!/usr/bin/env bash
# Regenerate the machine snapshots in packages/. These are reference data:
# what provision.sh actually installs is the hand-maintained core-apps.txt.
set -euo pipefail

DOTFILES_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

command -v dnf >/dev/null || { echo "ERROR: dnf not found; this script is Fedora-only." >&2; exit 1; }

echo "==> Snapshotting installed packages..."

fedora_ver="$(. /etc/os-release; echo "${VERSION_ID:-?}")"

# --userinstalled is the closest analogue of `pacman -Qne`: packages installed
# on purpose rather than pulled in as dependencies.
{
  echo "# Generated by scripts/backup.sh on $(date +%Y-%m-%d) — Fedora ${fedora_ver}."
  echo "# Reference only. Install list: packages/core-apps.txt"
  dnf repoquery --userinstalled --qf '%{name}\n' | sort -u
} > "$DOTFILES_DIR/packages/dnf-userinstalled.txt"

if command -v flatpak >/dev/null; then
  # packages/flatpak.txt is hand-curated (it is an install list), so this only
  # reports what is present for you to add by hand.
  echo "    flatpak apps installed (curate packages/flatpak.txt yourself):"
  flatpak list --app --columns=application,version | sed 's/^/      /'
fi

echo "==> Snapshot updated:"
echo "    - dnf (user-installed): $(grep -vc '^#' "$DOTFILES_DIR/packages/dnf-userinstalled.txt") packages"

echo ""
echo "==> Git Status:"
cd "$DOTFILES_DIR"
git status -s
